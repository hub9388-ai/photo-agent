test("original sliders apply to actual pixels, undo and export ZIP work", async ({ page }) => {
  const frame = await editor(page)
  await frame.getByRole("button", { name: "重置", exact: true }).click()
  const brightness = frame.getByRole("slider", { name: /^亮度/ })
  await brightness.fill("0.2")
  await brightness.blur()
  await frame.getByRole("button", { name: "应用", exact: true }).click()
  await expect(frame.getByRole("button", { name: "撤销", exact: true })).toBeEnabled()
  await page.getByRole("button", { name: "保存当前版本到素材库" }).click()
  await expect(page.getByRole("status")).toContainText("已保存到素材库")
  await frame.getByTitle("导出营销图和投放尺寸", { exact: true }).click()
  const downloadPromise = page.waitForEvent("download")
  await frame.getByRole("button", { name: /^打包 \d/ }).click()
  const data = await readFile((await (await downloadPromise).path())!)
  expect(data.readUInt32LE(0)).toBe(0x04034b50)
  const offset = 30 + data.readUInt16LE(26) + data.readUInt16LE(28)
  const png = data.subarray(offset, offset + data.readUInt32LE(18))
  expect(png.subarray(0, 8).toString("hex")).toBe("89504e470d0a1a0a")
  const samples = await page.evaluate(async base64 => {
    async function sample(src: string) {
      const image = new Image(); image.src = src; await image.decode()
      const canvas = document.createElement("canvas"); canvas.width = 768; canvas.height = 1024
      const ctx = canvas.getContext("2d")!; ctx.drawImage(image, 0, 0)
      return [...ctx.getImageData(300, 450, 1, 1).data]
    }
    return [await sample("/demo/cat-original.png"), await sample(`data:image/png;base64,${base64}`)]
  }, png.toString("base64"))
  expect(samples[1][0]).toBeGreaterThan(samples[0][0])
  await frame.getByRole("link", { name: "回编辑器" }).click()
  await frame.getByRole("button", { name: "撤销", exact: true }).click()
  await expect(frame.getByRole("button", { name: "重做", exact: true })).toBeEnabled()
})

