test("dashboard analysis handoff preserves photo, job and Post advice in editor import", async ({ page }) => {
  await page.addInitScript(() => {
    window.addEventListener("message", (event) => {
      if (event.data?.type === "photoai:import" && event.data.file instanceof File) {
        const { file, advice } = event.data
        sessionStorage.setItem("test.import-context", JSON.stringify({ name: file.name, size: file.size, type: file.type, advice }))
      }
    })
  })
  await page.goto("/")
  await page.getByRole("link", { name: /分析并优化照片/ }).click()
  await page.getByRole("button", { name: "开始智能分析" }).click()
  await expect(page.getByText("Post Agent（后期分析） 已完成", { exact: true })).toBeVisible()
  const handoff = page.getByRole("link", { name: "将当前照片送入修图工作台" })
  const target = new URL((await handoff.getAttribute("href"))!, "http://127.0.0.1:4175")
  expect(target.searchParams.get("media_id")).toBe("demo-cat-original")
  expect(target.searchParams.get("job_id")).toBe("demo-cat")
  await handoff.click()
  await page.getByRole("button", { name: "发送素材库照片", exact: true }).click()
  const frame = page.frameLocator('iframe[title="AI 修图编辑器"]')
  await expect(frame.getByRole("slider", { name: /^对比度/ })).toHaveValue("0.08")
  await expect(frame.getByRole("slider", { name: /^高光/ })).toHaveValue("-0.15")
  const context = await page.evaluate(() => JSON.parse(sessionStorage.getItem("test.import-context")!))
  expect(context.size).toBe((await readFile("public/demo/cat-original.png")).byteLength)
  expect(context.type).toBe("image/png")
  expect(context.advice.source_media_id).toBe("demo-cat-original")
  expect(context.advice.source_job_id).toBe("demo-cat")
  expect(context.advice.params).toMatchObject({ contrast: 0.08, highlights: -0.15, shadows: 0.1, saturation: -0.05 })
})
