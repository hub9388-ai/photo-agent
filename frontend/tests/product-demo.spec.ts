const failures = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const problems: string[] = []; failures.set(page, problems)
  page.on("pageerror", error => problems.push(error.message))
  page.on("request", request => {
    const url = new URL(request.url())
    if (["data:", "blob:"].includes(url.protocol)) return
    if (url.origin !== "http://127.0.0.1:4175" || /^\/(api|events)\//.test(url.pathname) || !["GET", "HEAD"].includes(request.method())) problems.push(`${request.method()} ${url.pathname}`)
  })
})
test.afterEach(async ({ page }) => { expect(failures.get(page), "No backend requests or browser errors").toEqual([]) })
