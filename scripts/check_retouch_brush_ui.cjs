const fs = require('node:fs')
const vm = require('node:vm')
const assert = require('node:assert/strict')
const ts = require('../frontend/node_modules/typescript')
const context = {exports:{}}
const file = 'integrations/ai-retouch-agent/frontend/src/lib/selectionHistory.ts'
vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,context)
const {createSelectionHistory, selectionRequests} = context.exports
const history = createSelectionHistory()
history.commit({kind:'stroke',points:[{x:.2,y:.3}],radius:.02,shape:'paint',operation:'add'})
history.commit({kind:'stroke',points:[{x:.5,y:.3}],radius:.08,shape:'paint',operation:'subtract'})
history.commit({kind:'stroke',points:[{x:.8,y:.3}],radius:.04,shape:'lasso',operation:'add'})
const undo = selectionRequests(history.undo(),7)
assert.equal(undo.length,2)
assert.equal(undo[0].radius,.02)
assert.equal(undo[1].radius,.08)
assert.equal(undo[1].operation,'subtract')
assert.equal(undo[1].shape,'paint')
const redo = selectionRequests(history.redo(),7)
assert.equal(redo.length,3)
assert.equal(redo[2].shape,'lasso')
assert.equal(redo[2].revision,7)
history.clear()
assert.equal(selectionRequests(history.current,7).length,0)
assert.equal(selectionRequests(history.undo(),7).length,3)
assert.equal(selectionRequests([{kind:'stroke',points:[{x:0,y:0}]}],7)[0].shape,'lasso')
console.log('PASS: undo/redo/clear replay retains ordered add/subtract, each stroke width/shape and revision; legacy circle semantics retained.')
